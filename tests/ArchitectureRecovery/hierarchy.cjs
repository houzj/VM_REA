function hierarchyFor(slug,edges){
 const layout=layouts[slug];if(!layout)throw Error('Explicit hierarchy missing: '+slug);
 const byId=new Map(edges.map(e=>[e.id,e])),seen=new Set();
 const children=layout.map(([title,lanes])=>({title,kind:'subsystem',children:lanes.map(([title,ids])=>({title,kind:'evidence-lane',children:ids.map(id=>{
  const e=byId.get(id);if(!e||seen.has(id))throw Error('Unknown or duplicate hierarchy edge: '+id);seen.add(id);
  return {title:e.from+' → '+e.to,kind:'edge',edgeId:id,classification:e.classification};
 })}))}));
 if(seen.size!==edges.length)throw Error('Hierarchy omits evidence edges');
 return {title:'主界面',kind:'ui-root',organization:'independent-reading-organization',meaning:'按主界面子系统组织证据；成员调用由叶节点对应的证据边表达。',children};
}
