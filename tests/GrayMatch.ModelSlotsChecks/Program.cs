using VisionPlugins.GrayMatch;

int n = 0;
void Check(bool p, string text) { if (!p) throw new Exception(text); Console.WriteLine($"PASS {++n}: {text}"); }
var store = new GrayMatchModelSlots();
Check(store.Change([9]) == GrayMatchModelSlots.InvalidArgument, "native constructor chosen=-1 rejects Change before Choose");
Check(store.Add([]) == GrayMatchModelSlots.InvalidArgument, "empty source Add rejected");
store.SetPendingName([65]);
byte[] data = [1, 2, 3];
Check(store.Add(data) == 0 && store.Count == 1, "first free slot Add increments count");
Check(store.NextFreeIndex() == 1, "native first free slot query");
Check(store.ReadName(0).NativeOutLength == 2 && store.ReadName(0).Name[0] == 65, "CandidateName includes null in native outLength");
Check(store.ReadSelected(0) == (0u, "1", 1), "SelectedModule native single-byte result");
Check(store.ReadData(0, 0).Code == 0xe0000012 && store.ReadData(0, 0).RequiredLength == 3, "CandidateData insufficient buffer returns E12 and required bytes");
Check(store.ReadData(0, 3).Data.SequenceEqual(data), "CandidateData exact bytes");
data[0] = 99;
Check(store.ActiveSnapshot()[0].Data[0] == 1, "source Add deep copies buffer");
store.SetPendingName([66]); store.Add([4]);
Check(store.SetSelected(0, 0) == 0 && store.ActiveSnapshot().Single().Index == 1, "selection flag controls outer 100-slot search");
store.Choose(0); store.Change([9]);
Check(store.Count == 2 && store.ActiveSnapshot().Single().Index == 1, "Change preserves selection and count");
store.SetSelected(0, 1);
Check(store.ActiveSnapshot()[0].Name[0] == 65 && store.ActiveSnapshot()[0].Data[0] == 9, "Change preserves original name");
Check(store.Rename([67]) == 0 && store.ActiveSnapshot()[0].Name[0] == 67, "native Rename only changes chosen name");
store.MoveDown(0);
Check(store.ActiveSnapshot()[0].Name[0] == 66 && store.ActiveSnapshot()[1].Name[0] == 67, "Down swaps entire model payload and name");
store.MoveUp(1);
Check(store.ActiveSnapshot()[0].Name[0] == 67 && store.ActiveSnapshot()[1].Name[0] == 66, "Up swaps entire model payload and name");
store.Delete(0);
Check(store.Count == 1 && store.ActiveSnapshot()[0].Index == 0 && store.ActiveSnapshot()[0].Name[0] == 66, "Delete compacts trailing source slots");
var snapshot = store.ActiveSnapshot(); snapshot[0].Data[0] = 123;
Check(store.ActiveSnapshot()[0].Data[0] == 4, "independent readonly snapshot transport owns copies");
store.Clear(); store.Add([8]);
Check(store.ActiveSnapshot()[0].Name[0] == 66, "Clear retains pendingName outside native cleared slot region");
Check(store.Change([7]) == 0 && store.ActiveSnapshot()[0].Data[0] == 7, "Clear retains chosen index outside cleared source slots");
Check(store.Choose(100) == GrayMatchModelSlots.InvalidArgument, "independent safety boundary avoids original index100 later OOB");
Check(store.SetPendingName(new byte[261]) == GrayMatchModelSlots.InvalidArgument, "independent oversized name safety rejection");
for (int i = 1; i < 100; i++) Check(store.Add([1]) == 0, $"native slot capacity {i + 1}");
Check(store.Add([1]) == GrayMatchModelSlots.Full && store.Count == 100, "native full error E0000326");
Check(store.NextFreeIndex() is null, "typed explicit missing result when native full query writes nothing");
store.Clear();
Check(store.Count == 0 && store.ActiveSnapshot().Count == 0, "Clear releases all active model payloads");
var unsafeName = new GrayMatchModelSlots();
unsafeName.SetPendingName(Enumerable.Repeat((byte)65, 260).ToArray()); unsafeName.Add([1]);
bool nameRejected = false;
try { unsafeName.ReadName(0); } catch (NotSupportedException) { nameRejected = true; }
Check(nameRejected, "independent full260 non-NUL name safely rejected, not native strlen parity");
var emptyDelete = new GrayMatchModelSlots(); emptyDelete.Add([1]);
Check(emptyDelete.Delete(99) == 0 && emptyDelete.Count == 0, "source Delete empty slot still decrements count");
Console.WriteLine($"PASS {n}; production normal source model-slot surface, not native allocator or string parser parity");
